package rdp

// vkScanCode maps a Win32 virtual-key code (what MaaCore's Win32 controller
// passes to the control unit) to an RDP set-1 scan code. Windows has no
// left/right information for the generic modifiers, so they map to the left
// variants; the explicit L/R codes are handled separately.
func vkScanCode(vk int32) (code byte, extended bool, ok bool) {
	if mapped, found := vkScanCodes[vk]; found {
		return mapped.code, mapped.extended, true
	}
	return 0, false, false
}

